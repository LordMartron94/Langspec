package toolchain

import (
	"fmt"
	"foundation/system"
	"langspec/dsl"
	"sort"
	"strings"
	"syntaxa"
)

// PRAGMA keys for the go_bindings toolchain (tool.go_bindings { ... } in .lspec).
const (
	GoBindingsToolName           = "go_bindings"
	GoBindingsOutputPathKey      = "output-path"
	GoBindingsPackageNameKey     = "package-name"
	GoBindingsNamespacePrefixKey = "namespace-prefix"
	GoBindingsEnableKey          = "enable"
)

/*
RunGoBindingsToolchain generates a Go source file with strongly-typed Token and
Node types and one const per lexical token and per grammar node from the compiled
spec. The generated file is written to the path and package specified in the
tool.go_bindings PRAGMA.

Use cases:
- Type-safe AST handling in downstream compilers (e.g. validation, codegen) without magic strings.
- Sharing token and node identity across packages that consume the same .lspec (import the generated package).
- Enabling switch/map keyed by Token or Node with compile-time exhaustiveness where applicable.

Prerequisites:
- compileResult must be a valid LangSpecCompileResult from a successful compile.
- The .lspec must contain a tool.go_bindings PRAGMA with enable = true, output-path, and package-name set.
- Relative output-path is resolved against cwd and ancestors (see resolveGoBindingsOutputPath) so repo-root paths like src/compiler/foo.go work when the generator runs from src/compiler.

Edge cases:
- Returns nil without error if no tool.go_bindings PRAGMA is present or enable is not "true".
- If the spec has no tokens (resp. no nodes), the generated file omits the Token (resp. Node) type and const block.
- Returns an error if output-path or package-name is missing when the toolchain is enabled.
*/
func RunGoBindingsToolchain(compileResult *dsl.LangSpecCompileResult) error {
	for _, pragma := range compileResult.CompiledToolPragmas {
		if pragma.ToolName == GoBindingsToolName {
			return processGoBindingsPragma(compileResult, pragma)
		}
	}
	return nil
}

func processGoBindingsPragma(compileResult *dsl.LangSpecCompileResult, pragma dsl.ToolPragma) error {
	// 1. Validate Enablement safely
	enabled, ok := pragma.Settings[GoBindingsEnableKey].(string)
	if !ok || enabled == "false" {
		return nil // Not enabled or missing (defaults to off)
	}
	if enabled != "true" {
		return fmt.Errorf("go_bindings: unexpected '%s' value: '%v'", GoBindingsEnableKey, pragma.Settings[GoBindingsEnableKey])
	}

	// 2. Validate Output Path
	outputPath, ok := pragma.Settings[GoBindingsOutputPathKey].(string)
	if !ok || strings.TrimSpace(outputPath) == "" {
		return fmt.Errorf("go_bindings toolchain enabled but missing or invalid '%s'", GoBindingsOutputPathKey)
	}

	// 3. Validate Package Name
	packageName, ok := pragma.Settings[GoBindingsPackageNameKey].(string)
	if !ok || strings.TrimSpace(packageName) == "" {
		return fmt.Errorf("go_bindings toolchain enabled but missing or invalid '%s'", GoBindingsPackageNameKey)
	}

	// 4. Extract Optional Namespace Prefix
	var typePrefix *string
	if prefix, hasPrefix := pragma.Settings[GoBindingsNamespacePrefixKey].(string); hasPrefix && strings.TrimSpace(prefix) != "" {
		typePrefix = &prefix
	}

	// 5. Resolve Path and Execute
	resolved, err := system.PathResolveWorkspace(outputPath)
	if err != nil {
		return fmt.Errorf("go_bindings path resolution failed for '%s': %w", outputPath, err)
	}

	return executeGoBindingsToolchain(compileResult, resolved, packageName, typePrefix)
}

func executeGoBindingsToolchain(
	compileResult *dsl.LangSpecCompileResult,
	outputPath string,
	packageName string,
	typePrefix *string,
) error {
	tokens := extractSortedTokens(compileResult.CompiledLexerSpec)
	nodes := extractSortedNodes(compileResult.CompiledGrammarPackage)

	prefix := ""
	if typePrefix != nil {
		prefix = *typePrefix
	}

	sourceCode := generateBindingsCode(packageName, prefix, tokens, nodes)

	if err := system.FileWriteString(outputPath, sourceCode); err != nil {
		return fmt.Errorf("failed to write go bindings file: %w", err)
	}

	return nil
}

func extractSortedTokens(lexerSpec *dsl.LexerSpec) []string {
	tokenSet := make(map[string]bool)
	ruleset := lexerSpec.Ruleset("default")
	for _, rule := range ruleset.GetRules() {
		tokenStr := fmt.Sprintf("%v", rule.Token)
		if tokenStr != "" {
			tokenSet[tokenStr] = true
		}
	}

	var tokens []string
	for t := range tokenSet {
		tokens = append(tokens, t)
	}
	sort.Strings(tokens)
	return tokens
}

func extractSortedNodes(grammarPkg dsl.GrammarPackage) []string {
	nodeSet := make(map[string]bool)
	seen := make(map[interface{}]bool)
	for _, g := range grammarPkg.Grammars {
		collectNodes(g, nodeSet, seen)
	}

	var nodes []string
	for n := range nodeSet {
		nodes = append(nodes, n)
	}
	sort.Strings(nodes)
	return nodes
}

func generateBindingsCode(packageName string, prefix string, tokens []string, nodes []string) string {
	var sb strings.Builder
	sb.WriteString("// Code generated by LangSpec. DO NOT EDIT.\n\n")
	sb.WriteString(fmt.Sprintf("package %s\n\n", packageName))

	writeTypeBlock(&sb, prefix, "Token", tokens)
	writeTypeBlock(&sb, prefix, "Node", nodes)

	return strings.TrimSpace(sb.String()) + "\n"
}

func writeTypeBlock(sb *strings.Builder, prefix string, kind string, items []string) {
	if len(items) == 0 {
		return
	}

	typeName := prefix + kind

	sb.WriteString(fmt.Sprintf("// %s represents a %s generated by LangSpec\n", typeName, kind))
	sb.WriteString(fmt.Sprintf("type %s string\n\n", typeName))
	sb.WriteString("const (\n")

	for _, item := range items {
		constName := item
		if prefix != "" {
			constName = fmt.Sprintf("%s_%s", prefix, item)
		}
		// Note: The constant name gets the prefix, but the string value remains the raw 'item'
		sb.WriteString(fmt.Sprintf("\t%s %s = \"%s\"\n", constName, typeName, item))
	}

	sb.WriteString(")\n\n")
}

func collectNodes[TToken, TNodeKind comparable](
	g *syntaxa.Grammar[TToken, TNodeKind],
	nodeSet map[string]bool,
	seen map[interface{}]bool,
) {
	if g == nil || seen[g] {
		return
	}
	seen[g] = true

	if g.OutputNodeKind != nil {
		nodeStr := fmt.Sprintf("%v", *g.OutputNodeKind)
		if nodeStr != "" {
			nodeSet[nodeStr] = true
		}
	}

	for _, child := range g.Children {
		collectNodes(child, nodeSet, seen)
	}
}
