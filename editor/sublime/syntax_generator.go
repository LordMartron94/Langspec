const headerLine = "# ======================================================\n"
const timeFormat = "2006-01-02 15:04:05 MST"

/* ExtractionConfig maps editor IR contexts to YAML scope and meta_scope strings for Sublime output. */
type ExtractionConfig[TContext any] struct {
	ExtractScope     func(TContext) string
	ExtractMetaScope func(TContext) string
}

type languageMetadata struct {
	Name           string   `yaml:"name"`
	FileExtensions []string `yaml:"file_extensions"`
	Scope          string   `yaml:"scope"`
	Version        int      `yaml:"version"`
}

type contextEntry struct {
	MetaScope      *string        `yaml:"meta_scope,omitempty"`
	Match          *string        `yaml:"match,omitempty"`
	Scope          string         `yaml:"scope,omitempty"`
	Push           any            `yaml:"push,omitempty"`
	Pop            any            `yaml:"pop,omitempty"`
	Set            any            `yaml:"set,omitempty"`
	Captures       map[int]string `yaml:"captures,omitempty"`
	Embed          string         `yaml:"embed,omitempty"`
	EmbedScope     string         `yaml:"embed_scope,omitempty"`
	Escape         *string        `yaml:"escape,omitempty"`
	EscapeCaptures map[int]string `yaml:"escape_captures,omitempty"`
	Include        *string        `yaml:"include,omitempty"`
}

type contextsSection struct {
	Contexts map[string][]contextEntry `yaml:"contexts"`
}

/*
GenerateSyntaxFile serializes editor IR to a Sublime Text .sublime-syntax YAML file at outputFile.
If pruneWarnings is non-nil, each unreachable context removed after reachability analysis is reported there (one line per context).
*/
func GenerateSyntaxFile[TObservation cmp.Ordered, TToken, TTokenRole, TLexerState, TNodeKind comparable, TContext any](
	ir *editor.EditorIR[TObservation, TToken, TTokenRole, TLexerState, TNodeKind, TContext],
	fileExtensions []string,
	baseScope string,
	outputFile string,
	config ExtractionConfig[TContext],
	pruneWarnings io.Writer,
) error {
	sb := &strings.Builder{}

	writeHeader(sb, ir.LanguageName, ir.LanguageVersion)

	if err := writeMetadata(sb, ir.LanguageName, fileExtensions, baseScope); err != nil {
		return err
	}

	if err := writeContexts(sb, ir.LanguageMachine, config, pruneWarnings); err != nil {
		return err
	}

	if err := system.FileWriteString(outputFile, sb.String()); err != nil {
		return fmt.Errorf("could not write definition to file: %w", err)
	}

	return nil
}

func writeHeader(sb *strings.Builder, name, version string) {
	sb.WriteString("%YAML 1.2\n---\n\n")
	sb.WriteString(headerLine)
	sb.WriteString("#  GENERATED BY LangSpec -- DO NOT EDIT MANUALLY\n")
	sb.WriteString(headerLine)
	fmt.Fprintf(sb, "#  DATE: %s\n", time.Now().Format(timeFormat))
	fmt.Fprintf(sb, "#  GENERATED FOR: %s @ %s\n", name, version)
	sb.WriteString(headerLine)
	sb.WriteString("\n")
}

func writeSectionHeader(sb *strings.Builder, headerContent string) {
	sb.WriteString(headerLine)
	fmt.Fprintf(sb, "#  %s\n", headerContent)
	sb.WriteString(headerLine)
}

func writeMetadata(sb *strings.Builder, name string, exts []string, baseScope string) error {
	writeSectionHeader(sb, "Language Metadata")
	meta := languageMetadata{
		Name:           name,
		FileExtensions: exts,
		Scope:          baseScope,
		Version:        2,
	}
	return encodeAndWriteYAML(sb, meta)
}

func writeContexts[TObservation cmp.Ordered, TContext any](
	sb *strings.Builder,
	machine editor.LanguageMachine[TObservation, TContext],
	config ExtractionConfig[TContext],
	pruneWarnings io.Writer,
) error {
	writeSectionHeader(sb, "Contexts & Rules")
	contextsMap := buildContextsMap(machine, config, pruneWarnings)
	section := contextsSection{Contexts: contextsMap}
	return encodeAndWriteYAML(sb, section)
}

func buildContextsMap[TObservation cmp.Ordered, TContext any](
	machine editor.LanguageMachine[TObservation, TContext],
	config ExtractionConfig[TContext],
	pruneWarnings io.Writer,
) map[string][]contextEntry {
	representatives, labelToRepresentative := minimizeStatesForEmission(machine, config)
	incomingMetaEdges := buildIncomingMetaEdges(representatives, labelToRepresentative, config)

	contextsMap := make(map[string][]contextEntry)
	baseEntriesByLabel := make(map[string][]contextEntry)
	baseSignatureToLabels := make(map[string][]string)

	repLabels := make([]string, 0, len(representatives))
	for label := range representatives {
		repLabels = append(repLabels, label)
	}
	sort.Strings(repLabels)

	for _, label := range repLabels {
		state := representatives[label]
		baseEntries := buildTransitionsRemapped(state.Transitions, config, labelToRepresentative, label)
		baseEntriesByLabel[label] = baseEntries

		sig := generateEntriesSignature(baseEntries)
		baseSignatureToLabels[sig] = append(baseSignatureToLabels[sig], label)
	}

	usedNames := make(map[string]bool, len(repLabels))
	for _, label := range repLabels {
		usedNames[label] = true
	}
	usedNames["prototype"] = true

	sharedNameBySignature := make(map[string]string)
	sharedPool := make(map[string][]contextEntry)

	baseSigs := make([]string, 0, len(baseSignatureToLabels))
	for sig := range baseSignatureToLabels {
		baseSigs = append(baseSigs, sig)
	}
	sort.Strings(baseSigs)

	for _, sig := range baseSigs {
		labels := baseSignatureToLabels[sig]
		sort.Strings(labels)

		entries := baseEntriesByLabel[labels[0]]
		if !shouldExtractSharedInclude(entries, len(labels)) {
			continue
		}

		sharedName := makeUniqueContextName(buildSharedContextName(labels, entries), usedNames)
		usedNames[sharedName] = true
		sharedNameBySignature[sig] = sharedName
		sharedPool[sharedName] = entries
	}

	for _, label := range repLabels {
		state := representatives[label]
		entries := baseEntriesByLabel[label]

		baseSig := generateEntriesSignature(entries)
		if sharedName, ok := sharedNameBySignature[baseSig]; ok {
			entries = []contextEntry{
				{Include: stringPtr(sharedName)},
			}
		}

		if state.ImmediatePushTarget != nil {
			pushTarget := determineContextLabel(state.ImmediatePushTarget.Label)
			if remapped, ok := labelToRepresentative[pushTarget]; ok {
				pushTarget = remapped
			}
			entries = append(entries, contextEntry{
				Match: stringPtr(`(?=[\s\S]*)`),
				Push:  []string{pushTarget},
			})
		}

		if metaScope := config.ExtractMetaScope(state.Context); metaScope != "" {
			mergedMeta := mergeInheritedSetChainMetaScope(metaScope, incomingMetaEdges[label])
			metaScope = mergedMeta
			if shouldSuppressContextMetaScopeForSetChain(metaScope, incomingMetaEdges[label]) {
			} else {
				entries = append([]contextEntry{{MetaScope: &metaScope}}, entries...)
			}
		}

		if state.HasFallthroughPop {
			popAmount := 1
			if state.FallthroughPopAmount > 0 {
				popAmount = state.FallthroughPopAmount
			}
			entries = append(entries, contextEntry{
				Match: stringPtr(`(?=\S)`),
				Pop:   popAmount,
			})
		}

		if state.HasFallbackInvalid {
			if scope := config.ExtractScope(state.FallbackInvalidContext); scope != "" {
				entries = append(entries, contextEntry{
					Match: stringPtr(`\S`),
					Scope: scope,
				})
			}
		}

		contextsMap[label] = entries
	}

	sharedNames := make([]string, 0, len(sharedPool))
	for name := range sharedPool {
		sharedNames = append(sharedNames, name)
	}
	sort.Strings(sharedNames)
	for _, name := range sharedNames {
		contextsMap[name] = sharedPool[name]
	}

	if len(machine.AmbientTransitions) > 0 {
		prototypeEntries := buildTransitionsRemapped(machine.AmbientTransitions, config, labelToRepresentative, "prototype")
		contextsMap["prototype"] = prototypeEntries
	}

	lexModeContexts := buildLexModeContexts(machine.LexerModeStates, config)
	for name, entries := range lexModeContexts {
		contextsMap[name] = entries
	}

	pruneUnreachableContexts(contextsMap, pruneWarnings)
	validateContextReferences(contextsMap)

	return contextsMap
}

const sublimeReservedContextMain = "main"
const sublimeReservedContextPrototype = "prototype"

func pruneUnreachableContexts(contextsMap map[string][]contextEntry, pruneWarnings io.Writer) {
	reachable := make(map[string]bool)
	var queue []string
	enqueue := func(name string) {
		if reachable[name] {
			return
		}
		if _, ok := contextsMap[name]; !ok {
			return
		}
		reachable[name] = true
		queue = append(queue, name)
	}

	enqueue(sublimeReservedContextMain)
	enqueue(sublimeReservedContextPrototype)

	for head := 0; head < len(queue); head++ {
		ctxName := queue[head]
		for _, ent := range contextsMap[ctxName] {
			for _, ref := range contextEntryReferencedContexts(ent) {
				enqueue(ref)
			}
		}
	}

	reserved := map[string]bool{
		sublimeReservedContextMain:      true,
		sublimeReservedContextPrototype: true,
	}

	var pruned []string
	for name := range contextsMap {
		if reserved[name] {
			continue
		}
		if !reachable[name] {
			pruned = append(pruned, name)
		}
	}
	if len(pruned) == 0 {
		return
	}
	sort.Strings(pruned)
	for _, name := range pruned {
		delete(contextsMap, name)
		if pruneWarnings != nil {
			fmt.Fprintf(pruneWarnings, "langspec sublime: pruning unreachable context %q\n", name)
		}
	}
}

func contextEntryReferencedContexts(ent contextEntry) []string {
	var out []string
	out = append(out, stringOrStringSliceToNames(ent.Push)...)
	out = append(out, stringOrStringSliceToNames(ent.Set)...)
	if ent.Include != nil && *ent.Include != "" {
		out = append(out, *ent.Include)
	}
	return out
}

func stringOrStringSliceToNames(v any) []string {
	if v == nil {
		return nil
	}
	switch x := v.(type) {
	case []string:
		return x
	case string:
		if x == "" {
			return nil
		}
		return []string{x}
	default:
		return nil
	}
}

func minimizeStatesForEmission[TObservation cmp.Ordered, TContext any](
	machine editor.LanguageMachine[TObservation, TContext],
	config ExtractionConfig[TContext],
) (map[string]editor.EditorState[TObservation, TContext], map[string]string) {
	stateByLabel := make(map[string]editor.EditorState[TObservation, TContext], len(machine.EditorStates))
	labels := make([]string, 0, len(machine.EditorStates))

	for _, state := range machine.EditorStates {
		label := determineContextLabel(state.Label)
		stateByLabel[label] = state
		labels = append(labels, label)
	}
	sort.Strings(labels)

	partitions := make(map[string]int, len(labels))
	initialSigToPartition := map[string]int{}
	nextPartitionID := 0

	for _, label := range labels {
		sig := localStateEmissionSignature(stateByLabel[label], config)
		id, ok := initialSigToPartition[sig]
		if !ok {
			id = nextPartitionID
			initialSigToPartition[sig] = id
			nextPartitionID++
		}
		partitions[label] = id
	}

	for {
		nextPartitions := make(map[string]int, len(labels))
		fullSigToPartition := map[string]int{}
		nextPartitionID = 0
		changed := false

		for _, label := range labels {
			sig := fullStateEmissionSignature(stateByLabel[label], partitions, config)
			id, ok := fullSigToPartition[sig]
			if !ok {
				id = nextPartitionID
				fullSigToPartition[sig] = id
				nextPartitionID++
			}
			nextPartitions[label] = id
			if nextPartitions[label] != partitions[label] {
				changed = true
			}
		}

		partitions = nextPartitions
		if !changed {
			break
		}
	}

	rootLabel := determineContextLabel(machine.RootState.Label)
	repByPartition := make(map[int]string)

	for _, label := range labels {
		pid := partitions[label]
		currentRep, exists := repByPartition[pid]
		if !exists || shouldPreferRepresentative(label, currentRep, rootLabel) {
			repByPartition[pid] = label
		}
	}

	labelToRepresentative := make(map[string]string, len(labels))
	representatives := make(map[string]editor.EditorState[TObservation, TContext], len(repByPartition))

	for _, label := range labels {
		rep := repByPartition[partitions[label]]
		labelToRepresentative[label] = rep
	}

	for _, rep := range repByPartition {
		representatives[rep] = stateByLabel[rep]
	}

	return representatives, labelToRepresentative
}

func shouldPreferRepresentative(candidate, current, rootLabel string) bool {
	if candidate == rootLabel {
		return true
	}
	if current == rootLabel {
		return false
	}
	if len(candidate) < len(current) {
		return true
	}
	if len(candidate) > len(current) {
		return false
	}
	return candidate < current
}

func localStateEmissionSignature[TObservation cmp.Ordered, TContext any](
	state editor.EditorState[TObservation, TContext],
	config ExtractionConfig[TContext],
) string {
	var sb strings.Builder

	metaScope := config.ExtractMetaScope(state.Context)
	sb.WriteString("meta=")
	sb.WriteString(metaScope)
	sb.WriteString("||")

	if state.ImmediatePushTarget != nil {
		sb.WriteString("imm=1||")
	} else {
		sb.WriteString("imm=0||")
	}

	fmt.Fprintf(&sb, "fall=%t:%d||", state.HasFallthroughPop, state.FallthroughPopAmount)
	fmt.Fprintf(&sb, "invalid_fallback=%t:%s||", state.HasFallbackInvalid, config.ExtractScope(state.FallbackInvalidContext))

	for _, tr := range state.Transitions {
		sb.WriteString(localTransitionEmissionSignature(tr, config))
		sb.WriteString("###")
	}

	return sb.String()
}

func fullStateEmissionSignature[TObservation cmp.Ordered, TContext any](
	state editor.EditorState[TObservation, TContext],
	partitions map[string]int,
	config ExtractionConfig[TContext],
) string {
	var sb strings.Builder

	metaScope := config.ExtractMetaScope(state.Context)
	sb.WriteString("meta=")
	sb.WriteString(metaScope)
	sb.WriteString("||")

	if state.ImmediatePushTarget != nil {
		targetLabel := determineContextLabel(state.ImmediatePushTarget.Label)
		fmt.Fprintf(&sb, "imm=%d||", partitions[targetLabel])
	} else {
		sb.WriteString("imm=-1||")
	}

	fmt.Fprintf(&sb, "fall=%t:%d||", state.HasFallthroughPop, state.FallthroughPopAmount)
	fmt.Fprintf(&sb, "invalid_fallback=%t:%s||", state.HasFallbackInvalid, config.ExtractScope(state.FallbackInvalidContext))

	for _, tr := range state.Transitions {
		sb.WriteString(fullTransitionEmissionSignature(tr, partitions, config))
		sb.WriteString("###")
	}

	return sb.String()
}

func localTransitionEmissionSignature[TObservation cmp.Ordered, TContext any](
	tr editor.EditorTransition[TObservation, TContext],
	config ExtractionConfig[TContext],
) string {
	var sb strings.Builder

	var regexStr string
	if tr.RegexPattern != nil {
		regexStr = *tr.RegexPattern
	} else {
		var err error
		regexStr, err = tr.OnPattern.ToRegEx()
		if err != nil {
			panic(fmt.Errorf("engine error encountered while converting pattern to RegEx: %w", err))
		}
	}

	if tr.IsLookahead {
		regexStr = "(?=" + regexStr + ")"
	}

	sb.WriteString(regexStr)
	sb.WriteString("||")
	sb.WriteString(config.ExtractScope(tr.MatchContext))
	sb.WriteString("||")
	sb.WriteString(capturesEmissionSignature(tr.Captures, config.ExtractScope))
	sb.WriteString("||")
	fmt.Fprintf(&sb, "op=%v||pop=%d||", tr.Operation, tr.PopAmount)

	if tr.ForeignPayload != nil {
		sb.WriteString(foreignPayloadEmissionSignature(tr.ForeignPayload, config))
	}
	sb.WriteString("||")

	return sb.String()
}

func fullTransitionEmissionSignature[TObservation cmp.Ordered, TContext any](
	tr editor.EditorTransition[TObservation, TContext],
	partitions map[string]int,
	config ExtractionConfig[TContext],
) string {
	var sb strings.Builder
	sb.WriteString(localTransitionEmissionSignature(tr, config))
	sb.WriteString("targets=")

	for _, target := range tr.Targets {
		targetLabel := determineContextLabel(target.Label)
		fmt.Fprintf(&sb, "%d,", partitions[targetLabel])
	}

	return sb.String()
}

func capturesEmissionSignature[TContext any](
	captures map[int]TContext,
	extractScope func(TContext) string,
) string {
	if len(captures) == 0 {
		return ""
	}

	keys := make([]int, 0, len(captures))
	for k := range captures {
		keys = append(keys, k)
	}
	sort.Ints(keys)

	var sb strings.Builder
	for _, k := range keys {
		fmt.Fprintf(&sb, "%d:%s,", k, extractScope(captures[k]))
	}
	return sb.String()
}

func foreignPayloadEmissionSignature[TObservation cmp.Ordered, TContext any](
	payload *editor.ForeignMachinePayload[TObservation, TContext],
	config ExtractionConfig[TContext],
) string {
	if payload == nil {
		return ""
	}

	var sb strings.Builder
	sb.WriteString("embed=")
	sb.WriteString(payload.MachineID)
	sb.WriteString("||embed_scope=")
	sb.WriteString(config.ExtractMetaScope(payload.MachineContext))
	sb.WriteString("||")

	escape, err := payload.EscapePattern.ToRegEx()
	if err != nil {
		panic(fmt.Errorf("failed to compile escape pattern: %w", err))
	}
	sb.WriteString("escape=")
	sb.WriteString(escape)
	sb.WriteString("||")

	if len(payload.EscapeCaptures) > 0 {
		sb.WriteString(capturesEmissionSignature(payload.EscapeCaptures, config.ExtractScope))
	}

	return sb.String()
}

func buildTransitionsRemapped[TObservation cmp.Ordered, TContext any](
	transitions []editor.EditorTransition[TObservation, TContext],
	config ExtractionConfig[TContext],
	labelToRepresentative map[string]string,
	sourceLabel string,
) []contextEntry {
	entries := make([]contextEntry, 0, len(transitions))
	for _, t := range transitions {
		entries = append(entries, buildSingleTransitionRemapped(t, config, labelToRepresentative, sourceLabel))
	}
	return entries
}

func buildSingleTransitionRemapped[TObservation cmp.Ordered, TContext any](
	t editor.EditorTransition[TObservation, TContext],
	config ExtractionConfig[TContext],
	labelToRepresentative map[string]string,
	sourceLabel string,
) contextEntry {
	var regexStr string
	if t.RegexPattern != nil {
		regexStr = *t.RegexPattern
	} else {
		var err error
		regexStr, err = t.OnPattern.ToRegEx()
		if err != nil {
			panic(fmt.Errorf("engine error encountered while converting pattern to RegEx: %w", err))
		}
	}

	if t.IsLookahead {
		regexStr = fmt.Sprintf("(?=%s)", regexStr)
	}

	entry := contextEntry{
		Match:    &regexStr,
		Scope:    config.ExtractScope(t.MatchContext),
		Captures: buildCapturesMap(t.Captures, config.ExtractScope),
	}

	applyStackOperationRemapped(&entry, t, config, labelToRepresentative)
	if onlySetTargetIsSource(entry.Set, sourceLabel) {
		entry.Set = nil
	}
	applyLexModeStack(&entry, t, labelToRepresentative)
	return entry
}

func lexModeSublimeLabel(stateName string) string {
	s := text.NewIdentifierSanitizer()
	return "lex__" + s.Sanitize(stateName)
}

func applyLexModeStack[TObservation cmp.Ordered, TContext any](
	entry *contextEntry,
	t editor.EditorTransition[TObservation, TContext],
	labelToRepresentative map[string]string,
) {
	_ = labelToRepresentative
	// Embed transitions are handled by the client machine selected via `embed`.
	// Applying additional lex-mode stack operations here is redundant and can
	// generate conflicting push/set directives in Sublime YAML.
	if entry.Embed != "" {
		return
	}
	// Sublime has a single context stack; combining parse stack ops (push/set/pop)
	// with lex-mode stack ops on the same rule can desynchronize parse progression.
	// Keep parse control-flow authoritative when present.
	if entry.Push != nil || entry.Set != nil || entry.Pop != nil {
		return
	}

	if t.LexPopAmount > 0 {
		if cur, ok := entry.Pop.(int); ok {
			entry.Pop = cur + t.LexPopAmount
		} else if entry.Pop == nil {
			entry.Pop = t.LexPopAmount
		} else {
			entry.Pop = t.LexPopAmount
		}
	}

	var curPush []string
	switch v := entry.Push.(type) {
	case []string:
		curPush = append([]string(nil), v...)
	}
	for _, s := range t.LexPushStates {
		lab := lexModeSublimeLabel(s)
		curPush = append(curPush, lab)
	}
	if len(curPush) > 0 {
		entry.Push = curPush
	}

	if len(t.LexSetStates) > 0 {
		set := make([]string, 0, len(t.LexSetStates))
		for _, s := range t.LexSetStates {
			lab := lexModeSublimeLabel(s)
			set = append(set, lab)
		}
		entry.Set = set
	}
}

func buildLexModeContexts[TObservation cmp.Ordered, TContext any](
	lexerModeStates []editor.EditorState[TObservation, TContext],
	config ExtractionConfig[TContext],
) map[string][]contextEntry {
	if len(lexerModeStates) == 0 {
		return nil
	}
	contexts := make(map[string][]contextEntry, len(lexerModeStates))
	for _, state := range lexerModeStates {
		label := determineContextLabel(state.Label)
		entries := buildTransitionsRemapped(state.Transitions, config, map[string]string{}, label)
		if metaScope := config.ExtractMetaScope(state.Context); metaScope != "" {
			entries = append([]contextEntry{{MetaScope: &metaScope}}, entries...)
		}
		if state.HasFallthroughPop {
			popAmount := 1
			if state.FallthroughPopAmount > 0 {
				popAmount = state.FallthroughPopAmount
			}
			entries = append(entries, contextEntry{
				Match: stringPtr(`(?=\S)`),
				Pop:   popAmount,
			})
		}
		if state.HasFallbackInvalid {
			if scope := config.ExtractScope(state.FallbackInvalidContext); scope != "" {
				entries = append(entries, contextEntry{
					Match: stringPtr(`\S`),
					Scope: scope,
				})
			}
		}
		contexts[label] = entries
	}
	return contexts
}

func onlySetTargetIsSource(v any, sourceLabel string) bool {
	if sourceLabel == "" || v == nil {
		return false
	}
	switch x := v.(type) {
	case string:
		return x == sourceLabel
	case []string:
		return len(x) == 1 && x[0] == sourceLabel
	default:
		return false
	}
}

func validateContextReferences(contextsMap map[string][]contextEntry) {
	for source, entries := range contextsMap {
		for _, ent := range entries {
			for _, target := range contextEntryReferencedContexts(ent) {
				if _, ok := contextsMap[target]; ok {
					continue
				}
				panic(fmt.Errorf("langspec sublime: context %q references missing context %q", source, target))
			}
		}
	}
}

type incomingMetaEdge struct {
	SourceMeta string
	Operation  editor.StackOperation
}

func buildIncomingMetaEdges[TObservation cmp.Ordered, TContext any](
	representatives map[string]editor.EditorState[TObservation, TContext],
	labelToRepresentative map[string]string,
	config ExtractionConfig[TContext],
) map[string][]incomingMetaEdge {
	incoming := make(map[string][]incomingMetaEdge)
	for _, sourceState := range representatives {
		sourceMeta := config.ExtractMetaScope(sourceState.Context)
		for _, tr := range sourceState.Transitions {
			for _, target := range tr.Targets {
				targetLabel := determineContextLabel(target.Label)
				if remapped, ok := labelToRepresentative[targetLabel]; ok {
					targetLabel = remapped
				}
				incoming[targetLabel] = append(incoming[targetLabel], incomingMetaEdge{
					SourceMeta: sourceMeta,
					Operation:  tr.Operation,
				})
			}
		}
	}
	return incoming
}

func shouldSuppressContextMetaScopeForSetChain(metaScope string, edges []incomingMetaEdge) bool {
	if metaScope == "" || len(edges) == 0 {
		return false
	}
	for _, edge := range edges {
		if edge.Operation != editor.STACK_SET {
			return false
		}
		if edge.SourceMeta == "" || edge.SourceMeta != metaScope {
			return false
		}
	}
	return true
}

func mergeInheritedSetChainMetaScope(metaScope string, edges []incomingMetaEdge) string {
	if metaScope == "" || len(edges) == 0 {
		return metaScope
	}
	inherited := ""
	for _, edge := range edges {
		if edge.Operation != editor.STACK_SET {
			return metaScope
		}
		if edge.SourceMeta == "" {
			return metaScope
		}
		if inherited == "" {
			inherited = edge.SourceMeta
			continue
		}
		if inherited != edge.SourceMeta {
			return metaScope
		}
	}
	if inherited == "" || inherited == metaScope {
		return metaScope
	}
	return inherited + " " + metaScope
}

func applyStackOperationRemapped[TObservation cmp.Ordered, TContext any](
	entry *contextEntry,
	t editor.EditorTransition[TObservation, TContext],
	config ExtractionConfig[TContext],
	labelToRepresentative map[string]string,
) {
	switch t.Operation {
	case editor.STACK_PUSH:
		entry.Push = determineContextLabelsRemapped(t.Targets, labelToRepresentative)
	case editor.STACK_POP:
		entry.Pop = t.PopAmount
	case editor.STACK_SET:
		entry.Set = determineContextLabelsRemapped(t.Targets, labelToRepresentative)
	case editor.STACK_EMBED:
		applyEmbedOperation(entry, t.ForeignPayload, config)
	case editor.STACK_NONE:
	}
}

func determineContextLabelsRemapped[TObservation cmp.Ordered, TContext any](
	targets []*editor.EditorState[TObservation, TContext],
	labelToRepresentative map[string]string,
) []string {
	out := make([]string, len(targets))
	for i, target := range targets {
		label := determineContextLabel(target.Label)
		if rep, ok := labelToRepresentative[label]; ok {
			label = rep
		}
		out[i] = label
	}
	return out
}

func shouldExtractSharedInclude(entries []contextEntry, useCount int) bool {
	if len(entries) == 0 || useCount < 2 {
		return false
	}

	// Single-entry contexts only start paying off when reused more than twice.
	if len(entries) == 1 {
		return useCount >= 3
	}

	return true
}

func buildSharedContextName(labels []string, entries []contextEntry) string {
	labelStem := deriveSharedLabelStem(labels)
	entryStem := deriveSharedEntryStem(entries)

	switch {
	case labelStem != "" && entryStem != "":
		return "shared__" + labelStem + "__" + entryStem
	case labelStem != "":
		return "shared__" + labelStem
	case entryStem != "":
		return "shared__" + entryStem
	default:
		return "shared__context"
	}
}

func deriveSharedLabelStem(labels []string) string {
	if len(labels) == 0 {
		return ""
	}

	tokenSets := make([][]string, 0, len(labels))
	for _, label := range labels {
		tokens := semanticLabelTokens(label)
		if len(tokens) > 0 {
			tokenSets = append(tokenSets, tokens)
		}
	}
	if len(tokenSets) == 0 {
		return ""
	}

	common := append([]string(nil), tokenSets[0]...)
	for i := 1; i < len(tokenSets); i++ {
		common = commonPrefix(common, tokenSets[i])
		if len(common) == 0 {
			break
		}
	}

	if len(common) == 0 {
		common = tokenSets[0]
	}

	if len(common) > 4 {
		common = common[:4]
	}

	return strings.Join(common, "_")
}

func deriveSharedEntryStem(entries []contextEntry) string {
	seen := map[string]bool{}
	parts := make([]string, 0, 3)

	for _, e := range entries {
		stem := scopeStem(e.Scope)
		if stem == "" && e.Match != nil {
			stem = regexStem(*e.Match)
		}
		if stem == "" || seen[stem] {
			continue
		}
		seen[stem] = true
		parts = append(parts, stem)
		if len(parts) == 3 {
			break
		}
	}

	return strings.Join(parts, "__")
}

func semanticLabelTokens(s string) []string {
	s = strings.ToLower(s)

	var normalized strings.Builder
	normalized.Grow(len(s))

	for i := 0; i < len(s); i++ {
		ch := s[i]
		if isAlphaNum(ch) {
			normalized.WriteByte(ch)
		} else {
			normalized.WriteByte('_')
		}
	}

	raw := strings.Split(normalized.String(), "_")
	out := make([]string, 0, len(raw))

	for _, part := range raw {
		if part == "" {
			continue
		}
		if isNoiseToken(part) {
			continue
		}
		if isNumericToken(part) {
			continue
		}
		if isHexLikeToken(part) {
			continue
		}
		out = append(out, part)
	}

	return out
}

func commonPrefix(a, b []string) []string {
	n := len(a)
	if len(b) < n {
		n = len(b)
	}

	i := 0
	for i < n && a[i] == b[i] {
		i++
	}
	return a[:i]
}

func scopeStem(scope string) string {
	if scope == "" {
		return ""
	}

	scope = strings.ReplaceAll(scope, ".", "_")
	tokens := semanticLabelTokens(scope)
	if len(tokens) == 0 {
		return ""
	}
	if len(tokens) > 4 {
		tokens = tokens[:4]
	}
	return strings.Join(tokens, "_")
}

func regexStem(regex string) string {
	var sb strings.Builder

	for i := 0; i < len(regex); i++ {
		ch := regex[i]
		if isAlphaNum(ch) {
			sb.WriteByte(ch)
			if sb.Len() >= 24 {
				break
			}
			continue
		}
		if sb.Len() > 0 {
			break
		}
	}

	return strings.ToLower(sb.String())
}

func makeUniqueContextName(base string, used map[string]bool) string {
	if base == "" {
		base = "shared__context"
	}

	name := base
	suffix := 2
	for used[name] {
		name = fmt.Sprintf("%s_%d", base, suffix)
		suffix++
	}
	return name
}

func isAlphaNum(ch byte) bool {
	return (ch >= 'a' && ch <= 'z') ||
		(ch >= 'A' && ch <= 'Z') ||
		(ch >= '0' && ch <= '9')
}

func isNumericToken(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return len(s) > 0
}

func isHexLikeToken(s string) bool {
	if len(s) < 6 {
		return false
	}
	for i := 0; i < len(s); i++ {
		ch := s[i]
		isHex := (ch >= '0' && ch <= '9') ||
			(ch >= 'a' && ch <= 'f') ||
			(ch >= 'A' && ch <= 'F')
		if !isHex {
			return false
		}
	}
	return true
}

func isNoiseToken(s string) bool {
	switch s {
	case "dummy", "state", "context", "ctx", "shared", "for":
		return true
	default:
		return false
	}
}

func generateEntriesSignature(entries []contextEntry) string {
	var sb strings.Builder
	for _, e := range entries {
		if e.Match != nil {
			sb.WriteString(*e.Match)
		}
		sb.WriteString("||")
		sb.WriteString(e.Scope)
		sb.WriteString("||")

		// Serialize Stack Ops
		fmt.Fprintf(&sb, "P%v:O%v:S%v||", e.Push, e.Pop, e.Set)

		// Serialize Captures Deterministically
		if len(e.Captures) > 0 {
			keys := make([]int, 0, len(e.Captures))
			for k := range e.Captures {
				keys = append(keys, k)
			}
			sort.Ints(keys)
			for _, k := range keys {
				fmt.Fprintf(&sb, "%d:%s,", k, e.Captures[k])
			}
		}
		sb.WriteString("||")

		// Serialize Embeds
		sb.WriteString(e.Embed)
		sb.WriteString("||")
		if e.Escape != nil {
			sb.WriteString(*e.Escape)
		}
		if e.MetaScope != nil {
			sb.WriteString("||meta:")
			sb.WriteString(*e.MetaScope)
		}
		sb.WriteString("###")
	}
	return sb.String()
}

// Helper to easily get a pointer to a string literal
func stringPtr(s string) *string {
	return &s
}

func buildCapturesMap[TContext any](
	captures map[int]TContext,
	extractScope func(TContext) string,
) map[int]string {
	if len(captures) == 0 {
		return nil
	}

	mapped := make(map[int]string, len(captures))
	for index, ctx := range captures {
		mapped[index] = extractScope(ctx)
	}
	return mapped
}

func applyEmbedOperation[TObservation cmp.Ordered, TContext any](
	entry *contextEntry,
	payload *editor.ForeignMachinePayload[TObservation, TContext],
	config ExtractionConfig[TContext],
) {
	if payload == nil {
		return
	}

	escapeStr, err := payload.EscapePattern.ToRegEx()
	if err != nil {
		panic(fmt.Errorf("failed to compile escape pattern: %w", err))
	}

	entry.Embed = payload.MachineID
	entry.EmbedScope = config.ExtractMetaScope(payload.MachineContext)
	entry.Escape = &escapeStr
	entry.EscapeCaptures = buildCapturesMap(payload.EscapeCaptures, config.ExtractScope)
}

func determineContextLabel(label string) string {
	if label == editor.ROOT_LABEL {
		return "main"
	}
	return label
}

func encodeAndWriteYAML(sb *strings.Builder, data any) error {
	value, err := yaml.Marshal(data)
	if err != nil {
		return fmt.Errorf("yaml marshal failed: %w", err)
	}
	sb.Write(value)
	sb.WriteString("\n")
	return nil
}
